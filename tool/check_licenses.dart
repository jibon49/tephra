import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import 'src/license_classifier.dart';

void main(List<String> args) {
  String? customConfig;
  var generateNotices = true;

  for (var i = 0; i < args.length; i++) {
    if (args[i] == '--config' && i + 1 < args.length) {
      customConfig = args[++i];
    } else if (args[i] == '--no-notices') {
      generateNotices = false;
    }
  }

  // 1. Locate repo root
  var dir = Directory.current;
  String? repoRoot;
  while (true) {
    final pubspec = File(p.join(dir.path, 'pubspec.yaml'));
    if (pubspec.existsSync()) {
      final content = pubspec.readAsStringSync();
      if (content.contains('name: tephra_workspace')) {
        repoRoot = dir.path;
        break;
      }
    }
    final parent = dir.parent;
    if (parent.path == dir.path) {
      break;
    }
    dir = parent;
  }

  if (repoRoot == null) {
    stderr.writeln(
      'Error: could not locate workspace root (pubspec.yaml with name: tephra_workspace)',
    );
    exit(2);
  }

  final configPath =
      customConfig ?? p.join(repoRoot, '.dart_tool', 'package_config.json');
  final configFile = File(configPath);
  if (!configFile.existsSync()) {
    stderr.writeln('Error: package config not found at $configPath');
    exit(2);
  }

  // 2. Read package config JSON
  final configJson =
      jsonDecode(configFile.readAsStringSync()) as Map<String, Object?>;
  final packageList = (configJson['packages'] as List<Object?>)
      .cast<Map<String, Object?>>();

  // 5. Locate flutterRoot
  final envFlutter = Platform.environment['FLUTTER_ROOT'];
  final flutterRoot = envFlutter != null
      ? p.normalize(envFlutter)
      : p.dirname(p.dirname(p.dirname(p.dirname(Platform.resolvedExecutable))));

  // 8. Read overrides
  final overridesFile = File(
    p.join(repoRoot, 'tool', 'license_overrides.json'),
  );
  Map<String, Object?> overridesMap = {};
  if (overridesFile.existsSync()) {
    try {
      final overridesJson =
          jsonDecode(overridesFile.readAsStringSync()) as Map<String, Object?>;
      overridesMap =
          (overridesJson['overrides'] as Map<String, Object?>?) ?? {};
    } catch (e) {
      stderr.writeln('Warning: failed to parse license_overrides.json: $e');
    }
  }

  final configParentDir = p.dirname(p.dirname(configPath));

  final results = <_PackageLicense>[];

  for (final pkg in packageList) {
    final name = pkg['name'] as String;
    final rootUri = pkg['rootUri'] as String;
    final resolvedUri = Uri.file(configPath)
        .resolve(rootUri.endsWith('/') ? rootUri : '$rootUri/');
    final pkgDir = p.normalize(resolvedUri.toFilePath());

    // 4. Skip workspace members and spike self-package
    if (p.isWithin(repoRoot, pkgDir) || p.equals(repoRoot, pkgDir)) {
      continue;
    }
    if (p.equals(configParentDir, pkgDir)) {
      continue;
    }

    final isSdk =
        p.isWithin(flutterRoot, pkgDir) || p.equals(flutterRoot, pkgDir);
    var kind = isSdk ? LicenceKind.flutterSdk : LicenceKind.unknown;

    // 6. Find licence file
    final licenseFilePath = _findLicenceFile(pkgDir, flutterRoot);
    String? licenseText;
    if (licenseFilePath != null) {
      licenseText = File(licenseFilePath).readAsStringSync();
      if (!isSdk) {
        kind = classifyLicenceText(licenseText);
      }
    } else {
      kind = LicenceKind.missing;
    }

    // 8. Check overrides
    if (overridesMap.containsKey(name)) {
      final overrideEntry = overridesMap[name] as Map<String, Object?>?;
      final overrideLabel = overrideEntry?['licence'] as String?;
      if (overrideLabel != null) {
        for (final k in LicenceKind.values) {
          if (k.label.toLowerCase() == overrideLabel.toLowerCase()) {
            kind = k;
            break;
          }
        }
      }
    }

    // 9. Read version
    var version = '-';
    final pkgPubspec = File(p.join(pkgDir, 'pubspec.yaml'));
    if (pkgPubspec.existsSync()) {
      final content = pkgPubspec.readAsStringSync();
      final match = RegExp(
        r'^version:\s*(\S+)',
        multiLine: true,
      ).firstMatch(content);
      if (match != null) {
        version = match.group(1) ?? '-';
      }
    }

    results.add(
      _PackageLicense(
        name: name,
        version: version,
        dir: pkgDir,
        kind: kind,
        licenseText: licenseText,
      ),
    );
  }

  results.sort((a, b) => a.name.compareTo(b.name));

  // 10. Generate THIRD_PARTY_NOTICES.md
  if (generateNotices) {
    final buffer = StringBuffer();
    buffer.write('# Third-party notices\n\n');
    buffer.write(
      'Generated by tool/check_licenses.dart — do not edit by hand.\n\n',
    );
    buffer.write('| Package | Version | Licence |\n');
    buffer.write('|---|---|---|\n');
    for (final r in results) {
      buffer.write('| ${r.name} | ${r.version} | ${r.kind.label} |\n');
    }
    buffer.write('\n');

    for (final r in results) {
      buffer.write('## ${r.name} ${r.version}\n\n');
      buffer.write('````\n');
      if (r.licenseText != null) {
        buffer.write(r.licenseText!.trimRight());
      } else {
        buffer.write('No license text found.');
      }
      buffer.write('\n````\n\n');
    }

    final noticesFile = File(p.join(repoRoot, 'THIRD_PARTY_NOTICES.md'));
    noticesFile.writeAsStringSync(buffer.toString());
  }

  // 11. Summary
  final allowedCount = results.where((r) => r.kind.allowed).length;
  final notAllowed = results.where((r) => !r.kind.allowed).toList();

  stdout.writeln(
    'Checked ${results.length} packages: $allowedCount allowed, ${notAllowed.length} not allowed.',
  );

  for (final r in notAllowed) {
    stdout.writeln(
      'NOT ALLOWED: ${r.name} ${r.version} (${r.kind.label}) ${r.dir}',
    );
  }

  if (notAllowed.isNotEmpty) {
    exit(1);
  }
}

String? _findLicenceFile(String packageDir, String flutterRoot) {
  const candidateNames = [
    'LICENSE',
    'LICENSE.md',
    'LICENSE.txt',
    'LICENCE',
    'LICENCE.md',
    'COPYING',
  ];

  var current = packageDir;
  for (var depth = 0; depth <= 2; depth++) {
    if (depth > 0) {
      final base = p.basename(current);
      if (base == 'pub.dev' || base == 'hosted') {
        break;
      }
    }

    for (final name in candidateNames) {
      final file = File(p.join(current, name));
      if (file.existsSync()) {
        return file.path;
      }
    }

    if (p.equals(current, flutterRoot)) {
      break;
    }

    final parent = p.dirname(current);
    if (p.equals(parent, current)) {
      break;
    }
    current = parent;
  }

  if (p.isWithin(flutterRoot, packageDir)) {
    for (final name in candidateNames) {
      final file = File(p.join(flutterRoot, name));
      if (file.existsSync()) {
        return file.path;
      }
    }
  }

  return null;
}

class _PackageLicense {
  _PackageLicense({
    required this.name,
    required this.version,
    required this.dir,
    required this.kind,
    required this.licenseText,
  });

  final String name;
  final String version;
  final String dir;
  final LicenceKind kind;
  final String? licenseText;
}
